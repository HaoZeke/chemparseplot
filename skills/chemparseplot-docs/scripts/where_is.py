"""Find the file to edit for a page of the chemparseplot manual.

    python scripts/where_is.py [PAGE ...]

PAGE is an address on https://chemparseplot.rgoswami.me/ (with or
without .html), a page name such as howto/install, or a file under
doc/source/ or docs/orgmode/. For each one the script prints the source
in the checkout and how the page is built from it. Without PAGE it does
that for every page the site map doc/source/llms.txt links, and exits 1
when one of them has no source. Standard library only.
"""

from __future__ import annotations

import ast
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
ORG = ROOT / "docs/orgmode"
MYST = ROOT / "doc/source"
SITE = "https://chemparseplot.rgoswami.me/"
PREFIXES = (SITE, "doc/source/", "docs/orgmode/", "/")
SUFFIXES = (".html", ".rst", ".md", ".org", ".ipynb")


def page_name(arg: str) -> str:
    page = arg.split("#", 1)[0].split("?", 1)[0]
    for prefix in PREFIXES:
        page = page.removeprefix(prefix)
    for suffix in SUFFIXES:
        page = page.removesuffix(suffix)
    if not page or page.endswith("/"):
        page += "index"
    return page


def org_excluded() -> re.Pattern[str] | None:
    """The :exclude regexp of the publishing project in docs/export.el."""
    export = (ROOT / "docs/export.el").read_text()
    m = re.search(r':exclude\s+"((?:[^"\\]|\\.)*)"', export)
    return re.compile(m[1].replace("\\\\", "\\")) if m else None


def sphinx_excluded() -> list[str]:
    """exclude_patterns of doc/source/conf.py."""
    tree = ast.parse((MYST / "conf.py").read_text())
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(
            isinstance(t, ast.Name) and t.id == "exclude_patterns" for t in node.targets
        ):
            return list(ast.literal_eval(node.value))
    return []


def rel(path: Path) -> str:
    return path.relative_to(ROOT).as_posix()


def locate(page: str) -> str | None:
    """Source of PAGE and how it is built, or None when there is none."""
    if page.startswith("apidocs/"):
        dotted = page.rsplit("/", 1)[-1]
        if not dotted.startswith("chemparseplot"):
            return "generated by sphinx-autodoc2 from the package; nothing to edit"
        base = ROOT.joinpath(*dotted.split("."))
        for path in (base.with_suffix(".py"), base / "__init__.py"):
            if path.is_file():
                return f"{rel(path)} (docstrings, read by sphinx-autodoc2)"
        return None
    excluded = org_excluded()
    org = ORG / f"{page}.org"
    if org.is_file() and not (excluded and excluded.search(f"{page}.org")):
        return f"{rel(org)} (Org, exported to doc/source/{page}.rst by docs/export.el)"
    md = MYST / f"{page}.md"
    if md.is_file():
        if f"{page}.md" in sphinx_excluded():
            return f"{rel(md)} (left out of the build by exclude_patterns in conf.py)"
        text = md.read_text(encoding="utf-8")
        kind = "executed by myst-nb" if "{code-cell}" in text else "MyST Markdown"
        return f"{rel(md)} ({kind})"
    return None


def site_map_pages() -> list[str]:
    site_map = (MYST / "llms.txt").read_text()
    links = re.findall(r"\]\((" + re.escape(SITE) + r"[^)\s]*)\)", site_map)
    return list(dict.fromkeys(page_name(link) for link in links))


def main(argv: list[str]) -> int:
    pages = [page_name(arg) for arg in argv] or site_map_pages()
    missing = 0
    for page in pages:
        where = locate(page)
        if where is None:
            missing += 1
            print(f"{page}: no source found")
        else:
            print(f"{page}: {where}")
    if not argv:
        print(f"{len(pages)} pages in doc/source/llms.txt, {missing} without a source")
    return 1 if missing else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
